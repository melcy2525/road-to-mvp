import { test, expect } from "@playwright/test";
import { mockCloud, login } from "./helpers/supabase";

test("自由メモをスマホで保存しPCで再表示・編集・削除でき、保存失敗時は本文を保つ", async ({ page, browser }) => {
  const mock = mockCloud();
  delete mock.backend.state.notes;
  await mock.install(page.context());
  await page.setViewportSize({ width: 390, height: 844 });
  await login(page);
  await page.getByRole("navigation", { name: "画面の切り替え" }).getByRole("button", { name: "メモ", exact: true }).click();
  await page.getByRole("button", { name: "メモを書く", exact: true }).click();
  const body = "相手の話を最後まで聞く\nアドバイス：質問をひとつ増やす";
  await page.getByLabel("メモの内容").fill(body);
  mock.backend.failSave = true;
  await page.getByRole("button", { name: "保存する", exact: true }).click();
  await expect(page.locator(".cloud-status").getByRole("status")).toContainText("保存に失敗");
  await expect(page.getByLabel("メモの内容")).toHaveValue(body);
  mock.backend.failSave = false;
  await page.getByRole("button", { name: "保存する", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await expect(page.locator(".memo-body")).toHaveText(body);
  const pc = await browser.newContext({ viewport: { width: 1440, height: 1080 } });
  await mock.install(pc);
  const other = await pc.newPage();
  await login(other);
  await other.locator(".sidebar nav").getByRole("button", { name: "メモ", exact: true }).click();
  await expect(other.locator(".memo-body")).toHaveText(body);
  await other.locator(".memo-card").getByRole("button", { name: "編集", exact: true }).click();
  await other.getByLabel("タイトル（任意）").fill("商談で意識すること");
  await other.getByLabel("メモの内容").fill(body + "\n毎朝読み返す");
  await other.getByRole("button", { name: "保存する", exact: true }).click();
  await expect(other.getByRole("dialog")).toHaveCount(0);
  await page.reload();
  await page.getByRole("navigation", { name: "画面の切り替え" }).getByRole("button", { name: "メモ", exact: true }).click();
  await expect(page.locator(".memo-card")).toContainText("毎朝読み返す");
  page.once("dialog", d => d.accept());
  await page.locator(".memo-card").getByRole("button", { name: "削除", exact: true }).click();
  await expect(page.locator(".memo-card")).toHaveCount(0);
  expect(mock.backend.state.notes).toEqual([]);
  await pc.close();
});
